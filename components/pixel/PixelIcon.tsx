export type PixelIconName = keyof typeof pixelIcons;
export type PixelIconSize = 16 | 20 | 24 | 32;
type Props = Omit<SVGProps<SVGSVGElement>, "name" | "width" | "height" | "viewBox" | "children" | "role" | "aria-hidden"> & {
  name: PixelIconName; size?: PixelIconSize;
};

/** Decorative by default; a supplied aria-label exposes a named image instead. */
export function PixelIcon({ name, size = 20, className = "", "aria-label": label, ...props }: Props) {
  return <svg {...props} data-pixel-icon={name} role={label ? "img" : undefined} aria-label={label}
    aria-hidden={label ? undefined : true} focusable="false" width={size} height={size} viewBox={`0 0 ${size} ${size}`}
    fill="currentColor" shapeRendering="crispEdges" className={`pixel-icon ${className}`}>
    <path d={pixelPath(pixelIcons[name], size)} />
  </svg>;
}
